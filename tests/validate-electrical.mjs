import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const html=readFileSync(new URL('../electrical.html',import.meta.url),'utf8');
const js=readFileSync(new URL('../electrical.js',import.meta.url),'utf8');
const data=JSON.parse(readFileSync(new URL('../data/electrical-reference.json',import.meta.url),'utf8'));
const catalogue=readFileSync(new URL('../catalogue.html',import.meta.url),'utf8');
const dashboard=readFileSync(new URL('../app.js',import.meta.url),'utf8');
assert(html.includes('id="localPdf"') && html.includes('id="fuses"') && html.includes('id="harnessSearch"'));
assert(html.includes('src="electrical.js"'),'Electrical page must load its audited controller');
assert(js.includes('data/electrical-reference.json'),'Electrical controller must load the curated data');
assert.equal(data.fuses.length,9);
assert.equal(data.harnessItems.length,51);
assert.equal(data.diagrams.length,6);
assert.equal(data.candidateParts.filter(x=>x.assembly==='Electrical Equipment').length,8);
assert(data.fuses.some(x=>x.position===7 && x.amp===25),'ABS fuse 7/25A missing');
assert(data.candidateParts.some(x=>x.partNumber==='T2501787'),'Original electrical catalogue candidate missing');
assert(catalogue.includes('categorySearch')&&catalogue.includes('motorcyclespareparts.eu'));
assert(dashboard.includes('renderComponentEvidence'),'Selected-part technical references must remain linked');
assert(!/VIN\s*[:=]\s*[A-HJ-NPR-Z0-9]{17}/i.test(html+js+dashboard),'Private identifiers must not appear in code');
console.log('PASS: 9 fuses, 51 harness components, 6 manual drawings, 8 electrical parts and document navigation.');
